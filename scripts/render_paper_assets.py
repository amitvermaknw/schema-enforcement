#!/usr/bin/env python3
r"""
paper/generated/paper_numbers.json -> paper/generated/
    numbers.tex            \pn{key} macros for every scalar (unknown key = LaTeX error)
    tab_*.tex              every results table in the paper and appendix
    fig_profiles.pdf       failure composition by model@tier
    keys.txt               list of defined keys (used by lint_numbers.py)

Key scheme:  groups -> g.<model>@<tier>.<field>      cells  -> c.<model>@<tier>@<domain>.<field>
             models -> m.<model>.<field>             nested dicts / lists -> dotted path / index
"""
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

GEN = Path("paper/generated")
N = json.loads((GEN / "paper_numbers.json").read_text())["numbers"]
V = {k: e["value"] for k, e in N.items()}
CATS = ["markdown_wrap", "length_bound", "regex_pattern", "schema_mirroring",
        "prose_preamble", "enum_violation", "parse_error"]
MEDIUM_ORDER_KEY = "rate"


def esc(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&"),
                 ("#", r"\#"), ("$", r"\$"), ("{", r"\{"), ("}", r"\}")):
        s = s.replace(a, b)
    return s


def pct(x, d=1):
    return f"{100 * x:.{d}f}\\%"


def num(x):
    return f"{x:,}".replace(",", "{,}")


def fmt(key: str, v):
    leaf = key.split(".")[-1]
    if v is None or isinstance(v, bool):
        return None
    if isinstance(v, int):
        return num(v)
    if isinstance(v, float):
        if leaf == "pp" or leaf.endswith("_pp"):
            return f"{v:.1f}"
        if leaf == "attempts_per_run":
            return f"{v:.2f}"
        return pct(v) if 0.0 <= v <= 1.0 else f"{v:.2f}"
    if isinstance(v, str):
        return esc(v) if v.isascii() else None
    if isinstance(v, list) and len(v) == 2 and all(isinstance(x, float) for x in v):
        return f"[{100 * v[0]:.1f}, {100 * v[1]:.1f}]"
    return None


def flatten(prefix, v, out):
    if isinstance(v, dict):
        for k, x in v.items():
            flatten(f"{prefix}.{k}", x, out)
        return
    if isinstance(v, list) and v and all(isinstance(x, dict) for x in v):
        for i, x in enumerate(v):
            flatten(f"{prefix}.{i}", x, out)
        return
    s = fmt(prefix, v)
    if s is not None:
        out[prefix] = s


def macros():
    out = {}
    for k, v in V.items():
        if k in ("groups", "cells", "models"):
            continue
        flatten(k, v, out)
    for g in V["groups"]:
        flatten(f'g.{g["model"]}@{g["tier"]}', {k: x for k, x in g.items() if k not in ("model", "tier")}, out)
    for c in V["cells"]:
        flatten(f'c.{c["model"]}@{c["tier"]}@{c["domain"]}',
                {k: x for k, x in c.items() if k not in ("model", "tier", "domain")}, out)
    for m in V["models"]:
        flatten(f'm.{m["model"]}', {k: x for k, x in m.items() if k != "model"}, out)
    lines = [r"% generated by scripts/render_paper_assets.py — do not edit",
             r"\newcommand{\pn}[1]{\ifcsname pn@#1\endcsname\csname pn@#1\endcsname"
             r"\else\PackageError{numbers}{Unknown number key #1}{Regenerate paper_numbers.json}\fi}"]
    lines += [rf"\expandafter\def\csname pn@{k}\endcsname{{{s}}}" for k, s in sorted(out.items())]
    (GEN / "numbers.tex").write_text("\n".join(lines) + "\n")
    (GEN / "keys.txt").write_text("\n".join(sorted(out)) + "\n")


def table(name, spec, header, rows, extra_mid=None):
    body = [r"\begin{tabular}{" + spec + "}", r"\toprule", header + r" \\", r"\midrule"]
    body += [r + r" \\" for r in rows]
    if extra_mid:
        body += [r"\midrule"] + [r + r" \\" for r in extra_mid]
    body += [r"\bottomrule", r"\end{tabular}"]
    (GEN / f"{name}.tex").write_text("\n".join(body) + "\n")


def code(s):
    return r"\code{" + esc(s) + "}"


def tab_models():
    rows = sorted((g for g in V["groups"] if g["tier"] == "medium"), key=lambda g: g["rate"])
    table("tab_models", "@{}lrrrll@{}",
          r"Model & Att. & Fail & Rate & Wilson 95\% & Dominant category (share)",
          [f'{code(g["model"])} & {num(g["attempts"])} & {num(g["failures"])} & {pct(g["rate"])} & '
           f'{fmt("ci", g["ci"])} & \\cat{{{esc(g["dominant"])}}} {pct(g["dominant_share"])}' for g in rows])


def tab_categories():
    tot = V["reported.failures"]
    rows = [f"\\cat{{{esc(c)}}} & {num(V[f'reported.cat.{c}'])} & {pct(V[f'reported.cat.{c}'] / tot)}"
            for c in CATS if f"reported.cat.{c}" in V]
    table("tab_categories", "@{}lrr@{}", r"Category & $n$ & Share", rows, [f"Total & {num(tot)} & "])


def tab_fence():
    models = sorted({k.split(".")[1] for k in V if k.startswith("fence.claude") and k.endswith(".n")})
    rows = []
    for m in models + ["reported"]:
        label = "All wrapped" if m == "reported" else code(m)
        rows.append(f"{label} & {num(V[f'fence.{m}.n'])} & {num(V[f'fence.{m}.pure'])} "
                    f"({pct(V[f'fence.{m}.pure_share'])}) & {num(V[f'fence.{m}.compound'])} "
                    f"({pct(V[f'fence.{m}.compound_share'])})")
    table("tab_fence", "@{}lrrr@{}", r"Model & Wrapped & Pure formatting & Compound", rows[:-1], rows[-1:])


def tab_ablation():
    vs = ["baseline", "aggressive", "few_shot"]
    r = lambda key: " & ".join(pct(V[f"ablation.{v}.{key}"]) for v in vs)  # noqa: E731
    table("tab_ablation", "@{}lrrr@{}", r"& Baseline & Aggressive & Few-shot",
          ["Attempts & " + " & ".join(num(V[f"ablation.{v}.attempts"]) for v in vs),
           r"\cat{markdown\_wrap} & " + r("markdown_wrap"),
           r"\cat{length\_bound} (primary) & " + r("length_bound"),
           r"\cat{regex\_pattern} & " + r("regex_pattern"),
           "Failure rate & " + r("failure_rate")],
          ["Length violations, primary + concealed & " + r("length_bound_incl_concealed")])


def tab_calibration():
    rows = []
    for c in ("length_bound", "regex_pattern", "prose_preamble", "enum_violation"):
        cells = []
        for t in ("medium", "medium_v2"):
            n, a = V[f"calib.{t}.{c}"], V[f"calib.{t}.attempts"]
            cells.append(f"{num(n)} & {pct(n / a)}")
        rows.append(f"\\cat{{{esc(c)}}} & " + " & ".join(cells))
    tot = " & ".join(f'{num(V[f"calib.{t}.failures"])} & {pct(V[f"calib.{t}.rate"])}' for t in ("medium", "medium_v2"))
    (GEN / "tab_calibration.tex").write_text("\n".join([
        r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
        f'& \\multicolumn{{2}}{{c}}{{medium ({num(V["calib.medium.attempts"])} att.)}} '
        f'& \\multicolumn{{2}}{{c}}{{medium\\_v2 ({num(V["calib.medium_v2.attempts"])} att.)}} \\\\',
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}", r"Category & $n$ & rate & $n$ & rate \\", r"\midrule",
        *[x + r" \\" for x in rows], r"\midrule", f"All failures & {tot} \\\\", r"\bottomrule", r"\end{tabular}"]) + "\n")


def tab_manifest():
    rows = [f'{code(c["model"])} & {esc(c["tier"])} & {esc(c["domain"])} & {num(c["runs"])} & '
            f'{num(c["attempts"])} & {num(c["failures"])} & {"pilot (excluded)" if c["excluded"] else ""}'
            for c in sorted(V["manifest"], key=lambda c: (c["tier"], c["model"], c["domain"]))]
    table("tab_manifest", "@{}lllrrrl@{}", "Model & Tier & Domain & Runs & Att. & Fail & Status", rows)


def tab_domains():
    rows = [f'{code(c["model"])} & {esc(c["tier"])} & {esc(c["domain"])} & {num(c["attempts"])} & '
            f'{pct(c["rate"])} & {c["attempts_per_run"]:.2f} & \\cat{{{esc(c["dominant"] or "--")}}}'
            for c in sorted(V["cells"], key=lambda c: (c["model"], c["tier"], c["domain"]))]
    table("tab_domains", "@{}lllrrrl@{}", "Model & Tier & Domain & Att. & Rate & Att./run & Dominant", rows)


def tab_first_attempt():
    rows = [f'{code(r["model"])} & {esc(r["tier"])} & {esc(r["node"])} & {num(r["reached"])} & '
            f'{pct(r["first_attempt_valid"])}' for r in V["first_attempt_by_node"]]
    table("tab_first_attempt", "@{}lllrr@{}", "Model & Tier & Node & Reached & First-attempt valid", rows)


def tab_validation():
    rows = []
    for c in CATS:
        d = V.get(f"validation.cat.{c}")
        if not d or not d["predicted"]:
            continue
        rows.append(f'\\cat{{{esc(c)}}} & {d["predicted"]} & {d["tp"]}/{d["predicted"]} & {d["tp"]}/{d["human"]}')
    table("tab_validation", "@{}lrll@{}", "Category & Predicted & Precision & Recall", rows)


def tab_perturbation():
    ts = ["medium", "medium_v3_loose_regex"]
    rows = [f"{lab} & " + " & ".join(num(V[f"pert.{t}.{k}"]) for t in ts)
            for lab, k in (("Leading digit", "leading_digit"), ("Length overflow", "length_overflow"),
                           ("Unicode contamination", "unicode"), ("Other character", "invalid_char"))]
    table("tab_perturbation", "@{}lrr@{}", "Sub-cause & Baseline pattern & Loosened pattern", rows,
          ["Violating identifiers & " + " & ".join(num(V[f"pert.{t}.identifiers"]) for t in ts)])


def tab_divergence():
    rows = [f'{esc(p["category"])} & {code(p["a"])} & {code(p["b"])} & {p["pp"]:.1f}'
            for p in V["divergence.top"][:8]]
    table("tab_divergence", "@{}lllr@{}", "Category & Group A & Group B & pp", rows)


def fig_profiles():
    plt.rcParams["pdf.fonttype"] = 42   # TrueType, not Type 3
    plt.rcParams["ps.fonttype"] = 42
    gs = sorted(V["groups"], key=lambda g: g["rate"])
    labels = [f'{g["model"]}@{g["tier"]}' for g in gs]
    fig, ax = plt.subplots(figsize=(6.5, 3.2))
    left = [0.0] * len(gs)
    for c in CATS:
        w = [g["composition"].get(c, 0) / g["failures"] if g["failures"] else 0 for g in gs]
        if any(w):
            ax.barh(labels, w, left=left, label=c)
            left = [a + b for a, b in zip(left, w)]
    ax.set_xlabel("Share of failures")
    ax.set_xlim(0, 1)
    ax.legend(fontsize=7, ncol=4, loc="upper center", bbox_to_anchor=(0.5, -0.18), frameon=False)
    ax.tick_params(axis="y", labelsize=7)
    fig.tight_layout()
    fig.savefig(GEN / "fig_profiles.pdf", bbox_inches="tight", pad_inches=0.02)


if __name__ == "__main__":
    macros()
    for f in (tab_models, tab_categories, tab_fence, tab_ablation, tab_calibration, tab_manifest,
              tab_domains, tab_first_attempt, tab_validation, tab_perturbation, tab_divergence):
        f()
    fig_profiles()
    print("rendered numbers.tex, keys.txt, tables, fig_profiles.pdf ->", GEN)
